import math
import time

ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"

# KUNCI RAHASIA KELOMPOK -- JANGAN DIBAGIKAN KEPADA KELOMPOK LAWAN
CAESAR_K = 22
AFFINE_A = 5
AFFINE_B = 8
VIGENERE_KEY = "MATEMATIKA"
TRANSPOSITION_KEY = [3, 1, 5, 2, 4]


def validate_text(text):
    text = text.upper().replace(" ", "")
    if not text or any(ch not in ALPHABET for ch in text):
        raise ValueError("Teks harus berisi huruf A-Z saja.")
    return text


def caesar_decrypt(text, k):
    return "".join(ALPHABET[(ALPHABET.index(ch) - k) % 26] for ch in text)


def affine_decrypt(text, a, b):
    if math.gcd(a, 26) != 1:
        raise ValueError("Kunci a harus relatif prima dengan 26.")
    inverse_a = pow(a, -1, 26)
    return "".join(
        ALPHABET[(inverse_a * (ALPHABET.index(ch) - b)) % 26]
        for ch in text
    )


def vigenere_decrypt(text, key):
    return "".join(
        ALPHABET[(ALPHABET.index(ch) -
                  ALPHABET.index(key[i % len(key)])) % 26]
        for i, ch in enumerate(text)
    )


def transposition_decrypt(text, key):
    ncols = len(key)
    nrows = (len(text) + ncols - 1) // ncols
    remainder = len(text) % ncols

    column_lengths = [
        nrows if col < remainder else nrows - 1
        for col in range(ncols)
    ]

    columns = [""] * ncols
    position = 0

    for rank in sorted(key):
        col = key.index(rank)
        length = column_lengths[col]
        columns[col] = text[position:position + length]
        position += length

    result = ""
    for row in range(nrows):
        for col in range(ncols):
            if row < len(columns[col]):
                result += columns[col][row]
    return result


def decrypt_composite(ciphertext):
    text = validate_text(ciphertext)
    stage1 = transposition_decrypt(text, TRANSPOSITION_KEY)
    stage2 = vigenere_decrypt(stage1, VIGENERE_KEY)
    stage3 = affine_decrypt(stage2, AFFINE_A, AFFINE_B)
    stage4 = caesar_decrypt(stage3, CAESAR_K)
    return stage1, stage2, stage3, stage4


# ---------- Eksekusi ----------
ciphertext = input("Masukkan ciphertext: ").strip()

# Pengukuran runtime dekripsi
waktu_mulai = time.perf_counter()
results = decrypt_composite(ciphertext)
waktu_selesai = time.perf_counter()
runtime_dekripsi = waktu_selesai - waktu_mulai

print("\nHASIL DEKRIPSI")
print("1. Setelah Transposisi^-1 :", results[0])
print("2. Setelah Vigenere^-1    :", results[1])
print("3. Setelah Affine^-1      :", results[2])
print("4. Plaintext              :", results[3])

CRIB = "RAHASIAKELOMPOKANDAADALAH"
if not results[3].startswith(CRIB):
    print("\nPERINGATAN: plaintext tidak diawali frasa", CRIB)

print(f"\nWaktu Eksekusi Dekripsi (1x)      : {runtime_dekripsi:.9f} detik ({runtime_dekripsi*1000:.6f} ms)")

N = 10000
waktu_mulai = time.perf_counter()
for _ in range(N):
    decrypt_composite(ciphertext)
t_dekripsi = (time.perf_counter() - waktu_mulai) / N
print(f"Waktu Eksekusi Dekripsi (rata-rata {N}x): {t_dekripsi:.9f} detik ({t_dekripsi*1000:.6f} ms)")

# ---------- Estimasi runtime kriptanalisis (brute-force) ----------
# Ruang kunci dari analisis di laporan/PPT
RUANG_KUNCI_TEORI   = 26 * 312 * 26**10 * 120   # K1 x K2 x K3 x K4
RUANG_KUNCI_EFEKTIF = 12 * 26**10 * 120         # k dan b terserap ke kunci Vigenere

DETIK_PER_TAHUN = 365.25 * 24 * 3600

for nama, ruang in [("Teori  ", RUANG_KUNCI_TEORI), ("Efektif", RUANG_KUNCI_EFEKTIF)]:
    total_detik = ruang * t_dekripsi
    print(f"Ruang kunci {nama}: {ruang:.3e}")
    print(f"  Estimasi brute-force : {total_detik:.3e} detik = {total_detik/DETIK_PER_TAHUN:.3e} tahun")
    print(f"  Rasio terhadap 1x dekripsi : {total_detik/t_dekripsi:.3e} kali")