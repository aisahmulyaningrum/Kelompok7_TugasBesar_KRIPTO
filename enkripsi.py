import math
import time

ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def validate_text(text):
    text = text.upper().replace(" ", "")
    if not text or any(ch not in ALPHABET for ch in text):
        raise ValueError("Teks harus berisi huruf A-Z saja (tanpa spasi/tanda baca).")
    return text


def caesar_encrypt(text, k):
    return "".join(ALPHABET[(ALPHABET.index(ch) + k) % 26] for ch in text)


def affine_encrypt(text, a, b):
    if math.gcd(a, 26) != 1:
        raise ValueError("Kunci a harus relatif prima dengan 26.")
    return "".join(
        ALPHABET[(a * ALPHABET.index(ch) + b) % 26] for ch in text
    )


def vigenere_encrypt(text, key):
    key = validate_text(key)
    return "".join(
        ALPHABET[(ALPHABET.index(ch) +
                  ALPHABET.index(key[i % len(key)])) % 26]
        for i, ch in enumerate(text)
    )


def transposition_encrypt(text, key):
    # Key berupa urutan angka unik, contoh: [3, 1, 5, 2, 4].
    if sorted(key) != list(range(1, len(key) + 1)):
        raise ValueError("Kunci transposisi harus berupa permutasi 1 sampai n.")
    ncols = len(key)
    return "".join(
        text[col::ncols]
        for _, col in sorted((rank, col) for col, rank in enumerate(key))
    )


def encrypt_composite(plaintext, caesar_k, affine_a, affine_b,
                      vigenere_key, transposition_key):
    text = validate_text(plaintext)
    stage1 = caesar_encrypt(text, caesar_k)
    stage2 = affine_encrypt(stage1, affine_a, affine_b)
    stage3 = vigenere_encrypt(stage2, vigenere_key)
    stage4 = transposition_encrypt(stage3, transposition_key)
    return stage1, stage2, stage3, stage4


# ---------- Eksekusi (kunci dimasukkan lewat input) ----------
print("ENKRIPSI KOMPOSIT")
print("Urutan: Caesar -> Affine -> Vigenere -> Transposisi")
print("Masukkan kunci yang ingin digunakan.")
plaintext = input("Plaintext: ").strip()
k = int(input("Kunci Caesar k (0-25): "))
a = int(input("Kunci Affine a: "))
b = int(input("Kunci Affine b (0-25): "))
vigenere_key = input("Kunci Vigenere (huruf A-Z): ").strip()
transposition_key = [
    int(x.strip()) for x in
    input("Kunci transposisi, pisahkan dengan koma (contoh 3,1,5,2,4): ").split(",")
]

# Pemeriksaan awalan teks standar (crib) dari dosen
CRIB = "RAHASIAKELOMPOKANDAADALAH"
if not validate_text(plaintext).startswith(CRIB):
    print("\nPERINGATAN: plaintext tidak diawali frasa", CRIB)

# Pengukuran runtime enkripsi
waktu_mulai = time.perf_counter()
results = encrypt_composite(plaintext, k, a, b, vigenere_key, transposition_key)
waktu_selesai = time.perf_counter()
runtime_enkripsi = waktu_selesai - waktu_mulai

print("\nHASIL SETIAP TAHAP")
print("1. Caesar      :", results[0])
print("2. Affine      :", results[1])
print("3. Vigenere    :", results[2])
print("4. Transposisi :", results[3])
print("\nCIPHERTEXT AKHIR:", results[3])

print(f"\nWaktu Eksekusi Enkripsi (1x)      : {runtime_enkripsi:.9f} detik ({runtime_enkripsi*1000:.6f} ms)")

# Rata-rata dari banyak pengulangan agar angkanya stabil
N = 10000
waktu_mulai = time.perf_counter()
for _ in range(N):
    encrypt_composite(plaintext, k, a, b, vigenere_key, transposition_key)
rata2 = (time.perf_counter() - waktu_mulai) / N
print(f"Waktu Eksekusi Enkripsi (rata-rata {N}x): {rata2:.9f} detik ({rata2*1000:.6f} ms)")